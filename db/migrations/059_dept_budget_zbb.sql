-- 3) Departmental Budget Pack report template ----------------------------------
INSERT INTO finance.report_template (template_key, name, purpose, audience, frequency, default_confidentiality, default_ai, effective_date, created_by)
VALUES
  ('DEPT_BUDGET_PACK', 'Departmental Budget Pack',
   'A department''s annual budget for SLT sign-off: target and planned spend, the initiatives and their objectives, and the zero-based cost detail (activity driver × quantity × unit cost) with monthly phasing.',
   'SLT, Finance Director, Department owners.', 'Annual or on submission', 'CONFIDENTIAL',
   '["FINANCE_DIRECTOR","FPA","COMMERCIAL_FINANCE"]'::jsonb, CURRENT_DATE, 'migration 059')
ON CONFLICT (template_key) DO NOTHING;

INSERT INTO finance.report_template_section (template_id, section_key, title, position, mandatory, default_source_key, default_ai_perspective, default_page_type)
SELECT t.template_id, s.section_key, s.title, s.position, s.mandatory, s.src, s.persp, s.ptype
FROM finance.report_template t
CROSS JOIN (VALUES
  ('cover',        'Cover Page',                    1, true,  NULL,          NULL,               'cover'),
  ('summary',      'Departmental Budget Summary',   2, true,  'dept_budget', 'FINANCE_DIRECTOR', 'exec_summary'),
  ('initiatives',  'Initiatives & Objectives',      3, true,  'dept_budget', 'COMMERCIAL_FINANCE','content'),
  ('zbb_detail',   'Zero-Based Cost Detail',        4, true,  'dept_budget', 'FPA',              'content')
) AS s(section_key, title, position, mandatory, src, persp, ptype)
WHERE t.template_key = 'DEPT_BUDGET_PACK'
ON CONFLICT (template_id, section_key) DO NOTHING;
