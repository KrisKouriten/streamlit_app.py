   '{"type":"object","additionalProperties":false,"required":["headline","summary","highlights","watch_items","recommended_focus","confidence","sources"],"properties":{"headline":{"type":"string"},"summary":{"type":"string"},"highlights":{"type":"array","items":{"type":"string"}},"watch_items":{"type":"array","items":{"type":"string"}},"recommended_focus":{"type":"array","items":{"type":"string"}},"confidence":{"type":"object","additionalProperties":false,"required":["level","reason"],"properties":{"level":{"type":"string","enum":["HIGH","MEDIUM","LOW"]},"reason":{"type":"string"}}},"sources":{"type":"array","items":{"type":"string"}}}}'::jsonb,
   'migration 041')
ON CONFLICT (prompt_code, version) DO NOTHING;

COMMIT;
