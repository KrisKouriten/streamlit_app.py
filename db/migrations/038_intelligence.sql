-- Migration 038 — Finance Intelligence Layer, Phase 1 (governed foundation)
-- The shared layer behind Finance Buddy and AI Perspective. This phase adds
-- only the governed foundation — configuration, the page-relationship registry,
-- run/source/claim/feedback records and seeds. NO chatbot UI and no new
-- financial calculations: the AI reuses the existing calculation services and
-- lands its outputs in the existing intelligence.ai_insight / action_register /
-- benefit_* tables (extend, don't duplicate).
--
-- Model choice lives in the DB (model_configuration) so it is swappable without
-- a deploy. Nothing here changes existing behaviour; every table is additive.
--
-- ROLLBACK:
