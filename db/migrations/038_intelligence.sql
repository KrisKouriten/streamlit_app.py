BEGIN;

-- Server-side model & tool configuration (CR §16). use_case ∈ ROUTING | PERSPECTIVE | BUDDY.
CREATE TABLE IF NOT EXISTS intelligence.model_configuration (
  config_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  use_case       varchar(32) NOT NULL,
  model          varchar(80) NOT NULL,           -- e.g. claude-haiku-4-5 / claude-sonnet-5 / claude-opus-5
  effort         varchar(12),                    -- low | medium | high | xhigh | max (advisory to the client)
  max_tokens     integer NOT NULL DEFAULT 4000,
  timeout_ms     integer NOT NULL DEFAULT 60000,
  prompt_code    varchar(48),                    -- FK-by-convention to prompt_version.prompt_code
  is_active      boolean NOT NULL DEFAULT true,
  effective_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes          text
);
CREATE INDEX IF NOT EXISTS ix_model_config_lookup ON intelligence.model_configuration (use_case, is_active, effective_date DESC);

-- Versioned prompts + output schemas (CR §16 — separate system instructions,
-- definitions and the output schema from the retrieved data and question).
CREATE TABLE IF NOT EXISTS intelligence.prompt_version (
  prompt_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prompt_code    varchar(48) NOT NULL,
  version        integer NOT NULL DEFAULT 1,
  system_prompt  text NOT NULL,
  output_schema  jsonb,                          -- json_schema for structured outputs (AI Perspective)
  is_active      boolean NOT NULL DEFAULT true,
  created_by     varchar(160),
  created_at     timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (prompt_code, version)
);

-- The governed page-relationship registry (CR §4.4). Held as configuration, not
-- hard-coded inside prompts.
CREATE TABLE IF NOT EXISTS intelligence.page_context_registry (
  page_id     varchar(60) PRIMARY KEY,
  page_name   varchar(120) NOT NULL,
  route       varchar(160),
  note        text,
  is_active   boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS intelligence.page_relationship (
  rel_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id       varchar(60) NOT NULL REFERENCES intelligence.page_context_registry(page_id) ON DELETE CASCADE,
  domain        varchar(48) NOT NULL,            -- a retrieval domain id (see lib/intelligence/retrieval.js)
  relation      varchar(12) NOT NULL DEFAULT 'RELATED',  -- PRIMARY | RELATED
  display_order integer NOT NULL DEFAULT 0,
  note          text,
  UNIQUE (page_id, domain)
);
CREATE INDEX IF NOT EXISTS ix_page_relationship_page ON intelligence.page_relationship (page_id, display_order);

-- Contextual suggested questions per page (CR §13).
CREATE TABLE IF NOT EXISTS intelligence.suggested_question (
  question_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id       varchar(60) NOT NULL,
  question      text NOT NULL,
  display_order integer NOT NULL DEFAULT 0,
  is_active     boolean NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS ix_suggested_question_page ON intelligence.suggested_question (page_id, display_order);

-- Interactive AI runs (Buddy / Perspective). Distinct from agent.agent_run (which
-- governs scheduled/rule agents with registry contracts); these are per-user,
-- per-request and permanently auditable (CR §15/§21.16).
CREATE TABLE IF NOT EXISTS intelligence.ai_run (
  run_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  surface       varchar(16) NOT NULL,            -- BUDDY | PERSPECTIVE
  user_id       bigint,                          -- public.users(id); no FK to keep the write cheap and non-blocking
  user_email    varchar(160),
  page_id       varchar(60),
  question_type varchar(24),
  question      text,
  filters       jsonb,
  model         varchar(80),
  prompt_code   varchar(48),
  confidence    varchar(12),                     -- HIGH | MEDIUM | LOW
  scope_note    text,
  status        varchar(16) NOT NULL DEFAULT 'RUNNING',  -- RUNNING | SUCCESS | FAILED | REFUSED
  summary       text,
  usage         jsonb,                           -- { input_tokens, output_tokens, ... }
  error         text,
  started_at    timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at   timestamptz
);
CREATE INDEX IF NOT EXISTS ix_ai_run_recent ON intelligence.ai_run (started_at DESC);
CREATE INDEX IF NOT EXISTS ix_ai_run_surface ON intelligence.ai_run (surface, started_at DESC);

CREATE TABLE IF NOT EXISTS intelligence.ai_run_step (
  step_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id      bigint NOT NULL REFERENCES intelligence.ai_run(run_id) ON DELETE CASCADE,
  step_no     integer NOT NULL,
  title       varchar(120) NOT NULL,
  detail      text,
  status      varchar(12) NOT NULL DEFAULT 'SUCCESS',  -- SUCCESS | FAILED | SKIPPED
  created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The sources cited by a run (CR §7 traceability).
CREATE TABLE IF NOT EXISTS intelligence.ai_source (
  source_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id       bigint NOT NULL REFERENCES intelligence.ai_run(run_id) ON DELETE CASCADE,
  label        varchar(160) NOT NULL,
  module       varchar(80),
  service      varchar(80),
  period       varchar(40),
  entity       varchar(120),
  store        varchar(120),
  scenario     varchar(60),
  data_through timestamptz,
  route        varchar(200)
);
CREATE INDEX IF NOT EXISTS ix_ai_source_run ON intelligence.ai_source (run_id);

-- The material numeric claims a run made, with the source they map to (CR §7).
CREATE TABLE IF NOT EXISTS intelligence.ai_claim (
  claim_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id       bigint NOT NULL REFERENCES intelligence.ai_run(run_id) ON DELETE CASCADE,
  statement    text NOT NULL,
  value_text   varchar(120),
  source_label varchar(160),
  verified     boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS ix_ai_claim_run ON intelligence.ai_claim (run_id);

-- User feedback on a response (CR §18).
CREATE TABLE IF NOT EXISTS intelligence.ai_feedback (
  feedback_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id       bigint NOT NULL REFERENCES intelligence.ai_run(run_id) ON DELETE CASCADE,
  rating       varchar(20) NOT NULL,             -- HELPFUL | PARTIAL | NOT_HELPFUL
  reason       varchar(40),                      -- INCORRECT_FIGURE | MISSING_CONTEXT | POOR_RECOMMENDATION | TOO_DETAILED | NOT_DETAILED | OTHER
  comment      text,
  user_email   varchar(160),
  created_at   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_ai_feedback_run ON intelligence.ai_feedback (run_id);

